package v1alpha1_test

// The spec.networking CEL rules are the only validation gate for the tenant network values:
// there is no admission webhook and no Go-side Validate(). A rule that fails to compile makes
// the whole CRD unappliable, and a rule that compiles but means the wrong thing is silent.
// Neither is something to discover on a live management cluster, so both CRD copies are
// compiled and evaluated here with the same apiextensions machinery the apiserver uses.
//
// This also pins the two copies together: crds/ is hand-maintained and ships to clusters,
// config/crd/bases/ is generated by controller-gen from the kubebuilder markers. Drift between
// them is a known footgun in this repository.

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	apiextensionsinternal "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions"
	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	structuralschema "k8s.io/apiextensions-apiserver/pkg/apiserver/schema"
	schemacel "k8s.io/apiextensions-apiserver/pkg/apiserver/schema/cel"
	"k8s.io/apimachinery/pkg/util/validation/field"
	celconfig "k8s.io/apiserver/pkg/apis/cel"
	"sigs.k8s.io/yaml"
)

// crdCopies are the two on-disk representations of the VirtualControlPlane CRD, relative to
// this package.
var crdCopies = map[string]string{
	"hand-maintained": "../../../../../crds/virtual_control_plane.yaml",
	"generated":       "../../config/crd/bases/control-plane.deckhouse.io_virtualcontrolplanes.yaml",
}

// networkingValidator compiles the CEL rules attached to spec.networking in the given CRD file.
// A compilation failure is reported as a fatal test error, because that is exactly what makes
// the CRD unappliable.
func networkingValidator(t *testing.T, path string) *schemacel.Validator {
	t.Helper()

	raw, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		t.Fatalf("read CRD: %v", err)
	}

	crd := &apiextensionsv1.CustomResourceDefinition{}
	if err := yaml.UnmarshalStrict(raw, crd); err != nil {
		t.Fatalf("unmarshal CRD: %v", err)
	}

	var props *apiextensionsv1.JSONSchemaProps
	for i := range crd.Spec.Versions {
		if crd.Spec.Versions[i].Name != "v1alpha1" {
			continue
		}
		if crd.Spec.Versions[i].Schema == nil {
			t.Fatal("v1alpha1 has no schema")
		}
		props = crd.Spec.Versions[i].Schema.OpenAPIV3Schema
	}
	if props == nil {
		t.Fatal("no v1alpha1 version found in CRD")
	}

	networking, ok := props.Properties["spec"].Properties["networking"]
	if !ok {
		t.Fatal("spec.networking not found in CRD schema")
	}
	if len(networking.XValidations) == 0 {
		t.Fatal("spec.networking carries no x-kubernetes-validations")
	}

	internalProps := &apiextensionsinternal.JSONSchemaProps{}
	if err := apiextensionsv1.Convert_v1_JSONSchemaProps_To_apiextensions_JSONSchemaProps(&networking, internalProps, nil); err != nil {
		t.Fatalf("convert schema: %v", err)
	}

	structural, err := structuralschema.NewStructural(internalProps)
	if err != nil {
		t.Fatalf("build structural schema: %v", err)
	}

	validator := schemacel.NewValidator(structural, true, celconfig.PerCallLimit)
	if validator == nil {
		t.Fatal("no CEL validator built from spec.networking")
	}
	return validator
}

func networking(service, pod, nodePrefix string) map[string]interface{} {
	return map[string]interface{}{
		"serviceSubnetCIDR":       service,
		"podSubnetCIDR":           pod,
		"podSubnetNodeCIDRPrefix": nodePrefix,
		"clusterDomain":           "cluster.virtual",
	}
}

func TestNetworkingCELRules(t *testing.T) {
	cases := []struct {
		name    string
		obj     map[string]interface{}
		wantErr bool
	}{
		{
			name: "deckhouse defaults are accepted",
			obj:  networking("10.96.0.0/12", "10.244.0.0/16", "24"),
		},
		{
			name: "adjacent ranges in the same /8 are accepted",
			obj:  networking("10.222.0.0/16", "10.244.0.0/16", "24"),
		},
		{
			name:    "node prefix equal to the pod prefix leaves no room for a node subnet",
			obj:     networking("10.96.0.0/12", "10.244.0.0/16", "16"),
			wantErr: true,
		},
		{
			name: "node prefix longer than the pod prefix is accepted",
			obj:  networking("10.96.0.0/12", "10.244.0.0/16", "20"),
		},
		{
			name:    "pod range nested inside the service range",
			obj:     networking("10.0.0.0/8", "10.244.0.0/16", "24"),
			wantErr: true,
		},
		{
			name:    "service range nested inside the pod range",
			obj:     networking("10.244.1.0/24", "10.244.0.0/16", "26"),
			wantErr: true,
		},
		{
			name:    "identical ranges",
			obj:     networking("10.244.0.0/16", "10.244.0.0/16", "24"),
			wantErr: true,
		},
		{
			// Host bits set. Both rules must reason about the masked network, the way every
			// consumer does, so this overlaps 10.244.0.0/16 and must be rejected.
			name:    "non-canonical service range still detected as overlapping",
			obj:     networking("10.244.5.7/16", "10.244.0.0/16", "24"),
			wantErr: true,
		},
	}

	for copyName, path := range crdCopies {
		t.Run(copyName, func(t *testing.T) {
			validator := networkingValidator(t, path)

			for _, tc := range cases {
				t.Run(tc.name, func(t *testing.T) {
					errs, _ := validator.Validate(
						context.Background(),
						field.NewPath("spec", "networking"),
						nil,
						tc.obj,
						nil,
						celconfig.RuntimeCELCostBudget,
					)
					if tc.wantErr && len(errs) == 0 {
						t.Fatalf("expected rejection, got none for %v", tc.obj)
					}
					if !tc.wantErr && len(errs) > 0 {
						t.Fatalf("expected acceptance, got %v", errs)
					}
				})
			}
		})
	}
}

// TestNetworkingCELRulesMatchAcrossCRDCopies pins the rule text itself, so a marker edit that is
// never regenerated into crds/ fails here rather than on a cluster.
func TestNetworkingCELRulesMatchAcrossCRDCopies(t *testing.T) {
	rules := map[string][]string{}

	for copyName, path := range crdCopies {
		raw, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			t.Fatalf("read %s CRD: %v", copyName, err)
		}
		crd := &apiextensionsv1.CustomResourceDefinition{}
		if err := yaml.UnmarshalStrict(raw, crd); err != nil {
			t.Fatalf("unmarshal %s CRD: %v", copyName, err)
		}
		for i := range crd.Spec.Versions {
			if crd.Spec.Versions[i].Name != "v1alpha1" || crd.Spec.Versions[i].Schema == nil {
				continue
			}
			networking := crd.Spec.Versions[i].Schema.OpenAPIV3Schema.Properties["spec"].Properties["networking"]
			for _, v := range networking.XValidations {
				rules[copyName] = append(rules[copyName], v.Rule)
			}
		}
	}

	hand, gen := rules["hand-maintained"], rules["generated"]
	if len(hand) != len(gen) {
		t.Fatalf("rule count differs: hand-maintained %v, generated %v", hand, gen)
	}
	for i := range hand {
		if hand[i] != gen[i] {
			t.Errorf("rule %d differs:\n  hand-maintained: %s\n  generated:       %s", i, hand[i], gen[i])
		}
	}
}
