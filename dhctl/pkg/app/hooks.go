package app

import "github.com/spf13/cobra"

// AfterApply chains hook into cmd.PreRunE, after the environment is applied.
// Several flag groups add their hooks to one command; they run in registration order.
func AfterApply(cmd *cobra.Command, hook func(cmd *cobra.Command) error) {
	prev := cmd.PreRunE
	cmd.PreRunE = func(c *cobra.Command, args []string) error {
		if prev != nil {
			if err := prev(c, args); err != nil {
				return err
			}
		}

		return hook(c)
	}
}
