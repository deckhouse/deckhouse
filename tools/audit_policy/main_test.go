func TestReplaceAutogeneratedBlock_NormalizesTrailingEmptyLines(t *testing.T) {
	content := strings.Join([]string{
		"prefix",
		autogenBlockStart,
		"old content",
		autogenBlockEnd,
		"",
		"",
		"",
		"suffix",
	}, "\n")

	block := strings.Join([]string{
		autogenBlockStart,
		"new content",
		autogenBlockEnd,
		"",
		"",
	}, "\n")

	got, err := replaceAutogeneratedBlock(content, block)
	if err != nil {
		t.Fatalf("replaceAutogeneratedBlock returned error: %v", err)
	}

	expected := strings.Join([]string{
		"prefix",
		autogenBlockStart,
		"new content",
		autogenBlockEnd,
		"",
		"suffix",
	}, "\n")

	if got != expected {
		t.Fatalf("unexpected replaced content:\n--- got ---\n%s\n--- expected ---\n%s", got, expected)
	}
}

func TestReplaceAutogeneratedBlock_Idempotent(t *testing.T) {
	content := strings.Join([]string{
		"prefix",
		autogenBlockStart,
		"old content",
		autogenBlockEnd,
		"",
		"suffix",
	}, "\n")

	block := strings.Join([]string{
		autogenBlockStart,
		"same content",
		autogenBlockEnd,
	}, "\n")

	once, err := replaceAutogeneratedBlock(content, block)
	if err != nil {
		t.Fatalf("first replaceAutogeneratedBlock returned error: %v", err)
	}
	twice, err := replaceAutogeneratedBlock(once, block)
	if err != nil {
		t.Fatalf("second replaceAutogeneratedBlock returned error: %v", err)
	}

	if once != twice {
		t.Fatalf("replaceAutogeneratedBlock is not idempotent:\n--- once ---\n%s\n--- twice ---\n%s", once, twice)
	}
}

func TestCompactRuleYAML_UsesTwoSpacesIndentation(t *testing.T) {
	rule := audit.PolicyRule{
		Level: audit.LevelMetadata,
		Resources: []audit.GroupResources{
			{
				Group:     "apps",
				Resources: []string{"deployments"},
			},
		},
	}

	yaml, err := compactRuleYAML(rule)
	if err != nil {
		t.Fatalf("compactRuleYAML returned error: %v", err)
	}

	if strings.Contains(yaml, "\t") {
		t.Fatalf("yaml contains tab indentation:\n%s", yaml)
	}
	if !strings.Contains(yaml, "\n  - group: apps\n") {
		t.Fatalf("yaml does not contain expected 2-space list indentation:\n%s", yaml)
	}
}

func TestDescriptionToHTMLTitle(t *testing.T) {
	cases := map[string]string{
		"Do not log health probes (`/readyz`, `/livez`).": "Do not log health probes (<code>/readyz</code>, <code>/livez</code>).",
		"Log all LIST operations.":                        "Log all LIST operations.",
		`Log "quoted" <names> & more`:                     "Log &#34;quoted&#34; &lt;names&gt; &amp; more",
	}

	for in, want := range cases {
		if got := descriptionToHTMLTitle(in); got != want {
			t.Fatalf("descriptionToHTMLTitle(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestBuildDetailedAuditRulesPage_RendersOfftopicBlocks(t *testing.T) {
	rules, err := cpmhooks.BuiltInAuditPolicyRulesForDocumentation()
	if err != nil {
		t.Fatalf("BuiltInAuditPolicyRulesForDocumentation returned error: %v", err)
	}

	for _, lang := range []string{"en", "ru"} {
		page, err := buildDetailedAuditRulesPage(rules, lang)
		if err != nil {
			t.Fatalf("buildDetailedAuditRulesPage(%s) returned error: %v", lang, err)
		}

		if got := strings.Count(page, "{% offtopic title=\""); got != len(rules) {
			t.Fatalf("%s page has %d offtopic blocks, want %d:\n%s", lang, got, len(rules), page)
		}
		if got := strings.Count(page, "{% endofftopic %}"); got != len(rules) {
			t.Fatalf("%s page has %d endofftopic tags, want %d", lang, got, len(rules))
		}
		if strings.Contains(page, "title=\"") && !strings.Contains(page, "<code>") {
			t.Fatalf("%s page titles do not render inline code as HTML", lang)
		}
		if strings.Contains(page, "title=\"`") || strings.Contains(page, "`\" %}") {
			t.Fatalf("%s page contains Markdown backticks in offtopic titles", lang)
		}
	}
}
